-- Persists engine/payout revisions and action idempotency independently of UI state.

ALTER TABLE game_rounds
  ADD COLUMN IF NOT EXISTS engine_version SMALLINT,
  ADD COLUMN IF NOT EXISTS payout_config_version SMALLINT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_chicken_road_dash_active_round
  ON game_rounds(user_id)
  WHERE game = 'chicken-road-dash' AND status = 'active';

CREATE TABLE IF NOT EXISTS chicken_road_dash_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id BIGINT NOT NULL REFERENCES game_rounds(id) ON DELETE RESTRICT,
  action_id UUID NOT NULL,
  action_seq INTEGER NOT NULL,
  action_type TEXT NOT NULL CHECK (action_type IN ('cross', 'cashout')),
  request_hash TEXT NOT NULL,
  response JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(round_id, action_id),
  UNIQUE(round_id, action_seq)
);

CREATE INDEX IF NOT EXISTS idx_chicken_road_dash_actions_round
  ON chicken_road_dash_actions(round_id, action_seq);
