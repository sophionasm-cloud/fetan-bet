-- Add private receipt references and an append-only review history.
-- This migration is additive; run it only against a reviewed non-production database first.
ALTER TABLE deposits ADD COLUMN IF NOT EXISTS receipt_key TEXT;

CREATE TABLE IF NOT EXISTS deposit_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deposit_id BIGINT NOT NULL REFERENCES deposits(id) ON DELETE RESTRICT,
  reviewer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  action TEXT NOT NULL CHECK (action IN ('approve', 'reject', 'escalate')),
  reason TEXT,
  verification JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_deposit_reviews_deposit ON deposit_reviews(deposit_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_deposit_reviews_reviewer ON deposit_reviews(reviewer_id, created_at DESC);

CREATE OR REPLACE FUNCTION block_deposit_review_modification()
RETURNS TRIGGER AS $$
BEGIN
  RAISE EXCEPTION 'Deposit review history is append-only';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_deposit_reviews_immutable ON deposit_reviews;
CREATE TRIGGER trg_deposit_reviews_immutable
BEFORE UPDATE OR DELETE ON deposit_reviews
FOR EACH ROW EXECUTE FUNCTION block_deposit_review_modification();
